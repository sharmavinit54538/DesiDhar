export function getProductImagesBySlug(slug: string): EnrichedProductImage[] {
  return PRODUCT_IMAGES[slug] || [];
}

export function getMainProductImage(slug: string): EnrichedProductImage | undefined {
  const list = PRODUCT_IMAGES[slug];
  if (!list || list.length === 0) return undefined;
  return list.find((img) => img.isMain) || list[0];
}

export function isProductAssetVerified(slug: string): boolean {
  const list = PRODUCT_IMAGES[slug];
  if (!list || list.length === 0) return false;
  return list[0].isVerifiedSpecific === true;
}
